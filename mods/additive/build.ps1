<#
.SYNOPSIS
  Builds additive stage containers: one registry (merged menu tables) plus one container per stage under its own
  package paths, so ported stages appear next to the vanilla ones (docs/additive-plan.md).

.DESCRIPTION
  Inputs : work\acr\specs\*.json (generated by scripts\gen-stage-specs.ps1)
           - Clone-only specs (no .Stage): relocate a vanilla Hafren copy (prototype / menu gate).
           - Port specs (.Stage = DR2 id): stage-build --additive, overlay on vanilla Hafren, relocate.
  Outputs: work\acr\additive\dist\zz_acrxs_registry_P.*
           work\acr\additive\dist\zz_acrxs_s_<id>_P.*
           work\acr\additive\check\verify.txt  (with -Verify)

.PARAMETER Stages  stage spec folder or files (default work\acr\specs; hand-written prototypes: mods\additive\stages-prototype)
.PARAMETER Only    build only these stage ids (the registry still lists every spec unless -PassedOnly)
.PARAMETER PassedOnly  registry lists only stages whose containers exist in dist (for batch builds)
.PARAMETER Verify  re-read the built containers with CUE4Parse and run the offline checks
#>
param(
    [string[]]$Stages,
    [string[]]$Only,
    [switch]$PassedOnly,
    [switch]$SkipRegistry,     # batch: build only the stage containers (scripts/build-stages.ps1 builds the registry once at the end)
    [switch]$RegistryOnly,     # batch: only (re)build the registry (+ -Verify) from the specs / containers that exist
    [switch]$KeepTemp,         # keep mod-build / overlay / mod-stage folders per stage (large)
    [switch]$SkipToolBuild,    # batch: acr-ref / acr-additive were already built
    [string]$Game = $(if ($env:ACR_GAME_DIR) { $env:ACR_GAME_DIR } else { 'C:\Program Files (x86)\Steam\steamapps\common\Assetto Corsa Rally' }),
    [string]$Retoc,
    [switch]$Verify
)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path "$PSScriptRoot\..\..").Path
$work = Join-Path $root 'work\acr\additive'
if ($Stages) { $Stages = @($Stages | % { $_ -split ',' } | ? { $_ }) }   # `pwsh -File build.ps1 -Stages a,b` arrives as one string
if ($Only) { $Only = @($Only | % { $_ -split ',' } | ? { $_ }) }
if (-not $Stages) { $Stages = @(Join-Path $root 'work\acr\specs') }
if (-not $Retoc) { $Retoc = Join-Path $root 'work\bin\bin\retoc.exe' }
if (-not (Test-Path $Retoc)) { throw "retoc not found at $Retoc" }
. (Join-Path $root 'mods\common\vanilla.ps1')

function Run([string]$exe) {
    # Out-Host: keep native stdout off the success stream so callers' return values stay clean
    & $exe @args 2>&1 | Out-Host
    if ($LASTEXITCODE -ne 0) { throw "$exe failed ($LASTEXITCODE)" }
}

function Copy-Tree([string]$src, [string]$dst) {
    if (-not (Test-Path $src)) { throw "missing $src" }
    New-Item -ItemType Directory -Force $dst | Out-Null
    # /E copies subdirs including empty; /XO not needed — we want overlay to win when called second
    & robocopy $src $dst /E /NFL /NDL /NJH /NJS /nc /ns /np | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy $src -> $dst failed ($LASTEXITCODE)" }
}

function New-StageOverlay([string]$VanillaLegacy, [string]$StageMod, [string]$Out) {
    # Full Hafren tree + BakedData + pacenote, then stage-build output on top (edited packages + Dr2 Tex/Mat).
    Remove-Item -Recurse -Force $Out -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force $Out | Out-Null
    foreach ($rel in @(
        'acr\Content\Levels\WalesS4HafrenSouth',
        'acr\Content\Environments\WalesS4HafrenSouth\DataAssets',
        'acr\Content\Data\Pacenote\Tables'
    )) {
        $s = Join-Path $VanillaLegacy $rel
        if (Test-Path $s) { Copy-Tree $s (Join-Path $Out $rel) }
    }
    # Also copy the single BakedData / pacenote files if they sit beside folders
    foreach ($rel in @(
        'acr\Content\Environments\WalesS4HafrenSouth\DataAssets\DA_WalesS4HafrenSouthBakedData.uasset',
        'acr\Content\Environments\WalesS4HafrenSouth\DataAssets\DA_WalesS4HafrenSouthBakedData.uexp',
        'acr\Content\Environments\WalesS4HafrenSouth\DataAssets\DA_WalesS4HafrenSouthBakedData.ubulk',
        'acr\Content\Data\Pacenote\Tables\DT_PacenoteHafrenSouthForward.uasset',
        'acr\Content\Data\Pacenote\Tables\DT_PacenoteHafrenSouthForward.uexp'
    )) {
        $s = Join-Path $VanillaLegacy $rel
        if (Test-Path $s) {
            $d = Join-Path $Out $rel
            New-Item -ItemType Directory -Force (Split-Path $d) | Out-Null
            Copy-Item $s $d -Force
        }
    }
    Copy-Tree $StageMod $Out
}

function Build-PortedStage($s, [string]$legacy, [string]$vanillaGame, [string]$acrRef, [string]$additiveTool) {
    $id = $s.Id
    $idLower = $id.ToLowerInvariant()
    $stageId = $s.Stage
    $ir = Join-Path $root "work\ir\$stageId"
    if (-not (Test-Path (Join-Path $ir 'stage.json'))) { throw "${id}: no stage IR at $ir (run dr2-extract stage-ir $stageId --render)" }
    $packageRoot = "/Game/AcrXs/Stages/$id"
    $mod = Join-Path $work "mod-build-$idLower"
    $report = Join-Path $work "stage-$idLower.report.json"
    Remove-Item -Recurse -Force $mod -ErrorAction SilentlyContinue

    # Texture templates live in the override pipeline's legacy-vanilla (same as mods/stage).
    $stageLegacy = Join-Path $root 'work\acr\legacy-vanilla'
    if (-not (Test-Path (Join-Path $stageLegacy 'acr\Content\Environments\WalesS4HafrenSouth\DataAssets\DA_WalesS4HafrenSouthBakedData.uasset'))) {
        throw "${id}: missing $stageLegacy - run mods\stage\build.ps1 -ExtractOnly once"
    }
    $surfaceReg = Join-Path $stageLegacy 'DA_PhysMaterialsMappingCommon.json'
    if (-not (Test-Path $surfaceReg)) {
        Run $acrRef export acr/Content/Data/Gameplay/PhysicalMaterials/DA_PhysMaterialsMappingCommon.uasset --game $vanillaGame --out $surfaceReg
    }

    $sbArgs = @(
        'stage-build', '--ir', $ir, '--legacy', $stageLegacy, '--out', $mod, '--report', $report,
        '--surface-registry', $surfaceReg, '--additive', '1', '--package-root', $packageRoot,
        '--objects', (Join-Path $root 'config\object-collision.toml'),
        '--pacenote-map', (Join-Path $root 'config\pacenote-map.toml'),
        '--pacenote-report', (Join-Path $work "pacenotes-$idLower.md"),
        '--respawn', 'relay',
        '--scenery', (Join-Path $root 'config\scenery.toml'), '--scenery-actor-hidden', '1',
        '--visuals', (Join-Path $root 'config\visuals.toml'), '--visuals-host', 'start', '--visuals-retarget', '1',
        '--visuals-vegetation', 'none', '--visuals-vista', '1', '--visuals-textured', '1',
        '--visuals-dr2', '1', '--visuals-canopies', 'apex', '--visuals-terrain-uv', 'box',
        '--visuals-ground', 'render', '--visuals-ground-lod', '1'
    )
    $skySection = if ($s.SkySection) { $s.SkySection } else { 'nz' }
    $sbArgs += @('--sky', (Join-Path $root 'config\sky.toml'), '--sky-section', $skySection)
    # --bounds: placement picks the rotation/height itself (host-region placement when the route fits Hafren's box, else an enlarged
    # PhysicsWorldBounds in the stage's own persistent-level clone); the spec's optional GroundOffset is added to the computed height.
    $sbArgs += @('--bounds', '1')
    $groundOffset = if ($null -ne $s.GroundOffset) { [double]$s.GroundOffset } else { 0 }
    if ($groundOffset -ne 0) { $sbArgs += @('--ground-offset', $groundOffset.ToString([Globalization.CultureInfo]::InvariantCulture)) }
    $bake = Join-Path $ir 'render\ground_bake\manifest.json'
    if (Test-Path $bake) { $sbArgs += @('--visuals-ground-bake', $bake) }
    Run $acrRef @sbArgs

    $overlay = Join-Path $work "overlay-$idLower"
    New-StageOverlay $legacy $mod $overlay

    $outMod = Join-Path $work "mod-stage-$idLower"
    Remove-Item -Recurse -Force $outMod -ErrorAction SilentlyContinue
    $relArgs = @('relocate', '--legacy', $overlay, '--out', $outMod)
    foreach ($p in $s.Clone.Packages.PSObject.Properties) { $relArgs += @('--map', "$($p.Name)=$($p.Value)") }
    foreach ($p in $s.Clone.Objects.PSObject.Properties) { $relArgs += @('--object', "$($p.Name)=$($p.Value)") }
    Run $additiveTool @relArgs
    # the overlay (full Hafren tree + stage-build output) is only relocate's input: drop it now, before the heavy retoc step
    if (-not $KeepTemp) { Remove-Item -Recurse -Force $overlay -ErrorAction SilentlyContinue }

    # Tex/Mat already live under /Game/AcrXs/Stages/<Id>/… (not relocated); copy into the stage container.
    foreach ($sub in @('Tex', 'Mat')) {
        $src = Join-Path $mod ("acr\Content\AcrXs\Stages\$id\$sub")
        if (Test-Path $src) { Copy-Tree $src (Join-Path $outMod "acr\Content\AcrXs\Stages\$id\$sub") }
    }
    # Menu.Images: route map, track map and elevation profile as UI textures under /Game/AcrXs/Stages/<Id>/Menu (docs/menu-images.md)
    if ($s.Menu -and $s.Menu.Images) {
        $menuArgs = @('menu-assets', '--ir', $ir, '--id', $id, '--legacy', $legacy, '--out', $outMod, '--preview', (Join-Path $root "work\acr\menu-preview\$id"))
        if ($s.Menu.Art) {
            $art = Join-Path $root "work\dr2\menu-art\frontend\streamed_textures\loading\$($s.Menu.Art).tpk"
            if (-not (Test-Path $art)) { & pwsh -NoProfile -File (Join-Path $root 'scripts\prepare-menu-art.ps1') | Out-Host }
            if (-not (Test-Path $art)) { throw "${id}: missing DR2 loading art $art" }
            $menuArgs += @('--art', $art)
        }
        Run $additiveTool @menuArgs
    }
    # stage-build output: its Tex/Mat are copied into $outMod above, nothing reads it after this point
    if (-not $KeepTemp) { Remove-Item -Recurse -Force $mod -ErrorAction SilentlyContinue }
    return $outMod
}

$specFiles = @($Stages | % { if (Test-Path $_ -PathType Container) { Get-ChildItem $_ -Filter *.json | % FullName } else { (Resolve-Path $_).Path } })
$specs = @($specFiles | % { Get-Content $_ -Raw | ConvertFrom-Json })
if (-not $specs) { throw "no stage specs in $Stages" }

$vanilla = New-VanillaView $Game (Join-Path $work 'vanilla')
$paks = Join-Path $vanilla 'acr\Content\Paks'

# legacy copies of the DB tables and of every package a stage clones
$legacy = Join-Path $work 'legacy'
$current = @(Get-ChildItem $paks -File -Filter '*.utoc' | % { "$($_.BaseName) $($_.Length)" })
$stamped = if (Test-VanillaStamp $legacy) { @((Get-Content (Join-Path $legacy '.source.json') -Raw | ConvertFrom-Json).containers) } else { @() }
if (-not $stamped -or (Compare-Object $stamped $current)) {
    Remove-Item -Recurse -Force $legacy -ErrorAction SilentlyContinue
}
$filters = @('Data/Database/Main/')
# templates of the generated menu textures (Menu.cs Images)
if (@($specs | ? { $_.Menu -and $_.Menu.Images })) { $filters += 'Data/UITextures/Tracks/Tracks/Wales' }
if (@($specs | ? { $_.Menu -and $_.Menu.Images -and $_.Menu.Art })) {
    $filters += @('Data/UITextures/Tracks/T_HafrenSouthBackground', 'Data/UITextures/Tracks/TracksImages/Wales/T_Severne',
        'Data/UITextures/Tracks/LobbyImages/SingleStage/Wales/T_Afon_Lobby')
}
# templates of the generated location tile / logo (MenuLocations.cs)
if (@($specs | ? { $_.Location.Template -and ($_.Location.TileArt -or $_.Location.GenLogo) })) {
    $filters += @('Data/UITextures/Tracks/T_WalesRally', 'Data/UITextures/Tracks/T_RallyWales')
}
foreach ($s in $specs) {
    if (-not $s.Clone -or -not $s.Clone.Packages) { continue }
    foreach ($p in $s.Clone.Packages.PSObject.Properties.Name) { $filters += $p.Substring('/Game/'.Length) }
}
$need = $filters | ? {
    $rel = 'acr\Content\' + ($_ -replace '/', '\')
    -not (Get-ChildItem (Join-Path $legacy $rel) -ErrorAction SilentlyContinue -Include *.uasset, *.umap -Recurse) -and
    -not (Test-Path (Join-Path $legacy ($rel + '.umap'))) -and
    -not (Test-Path (Join-Path $legacy ($rel + '.uasset')))
}
if ($need) {
    Assert-VanillaPaks $paks
    Run $Retoc to-legacy --version UE5_6 --no-shaders @($need | % { '--filter'; $_ }) $paks $legacy
}
Write-VanillaStamp $legacy $paks

$tool = Join-Path $root 'work\bin\acr-additive\acr-additive.exe'
$acrRef = Join-Path $root 'work\bin\acr-ref\acr-ref.exe'
if (-not $SkipToolBuild) {
    Run dotnet build (Join-Path $root 'tools\acr-additive\AcrAdditive.csproj') -c Release -o (Split-Path $tool) --nologo -v q
    Run dotnet build (Join-Path $root 'tools\acr-ref\AcrRef.csproj') -c Release -o (Split-Path $acrRef) --nologo -v q
}

$dist = Join-Path $work 'dist'
New-Item -ItemType Directory -Force $dist | Out-Null

# stages
$builtSpecs = @()
foreach ($s in $specs) {
    if ($RegistryOnly) { break }
    if ($Only -and $s.Id -notin $Only) { continue }
    $id = $s.Id.ToLowerInvariant()
    $outMod = $null
    try {
        if ($s.Stage) {
            $outMod = Build-PortedStage $s $legacy $vanilla $acrRef $tool
        }
        else {
            $outMod = Join-Path $work "mod-stage-$id"
            Remove-Item -Recurse -Force $outMod -ErrorAction SilentlyContinue
            $relArgs = @('relocate', '--legacy', $legacy, '--out', $outMod)
            foreach ($p in $s.Clone.Packages.PSObject.Properties) { $relArgs += @('--map', "$($p.Name)=$($p.Value)") }
            foreach ($p in $s.Clone.Objects.PSObject.Properties) { $relArgs += @('--object', "$($p.Name)=$($p.Value)") }
            Run $tool @relArgs
        }
        Remove-Item (Join-Path $dist "zz_acrxs_s_${id}_P.*") -ErrorAction SilentlyContinue
        Run $Retoc to-zen --version UE5_6 $outMod (Join-Path $dist "zz_acrxs_s_${id}_P.utoc")
        $builtSpecs += $s
    }
    finally {
        if (-not $KeepTemp) {
            # per-stage scratch is large (full Hafren tree + render meshes); the container in dist is the product.
            # In `finally` so a failed build does not leave ~0.4-0.9 GB per stage behind either.
            foreach ($d in @("mod-build-$id", "overlay-$id", "mod-stage-$id")) { Remove-Item -Recurse -Force (Join-Path $work $d) -ErrorAction SilentlyContinue }
        }
    }
}

# registry: vanilla tables + every selected spec (or only those with containers when -PassedOnly)
# Keep as Object[] so a single path is not splatted as characters into the registry CLI.
$regSpecs = [string[]]@(if ($PassedOnly) {
    $specFiles | % {
        $sp = Get-Content $_ -Raw | ConvertFrom-Json
        $id = $sp.Id.ToLowerInvariant()
        if (Test-Path (Join-Path $dist "zz_acrxs_s_${id}_P.utoc")) { $_ }
    }
} else { $specFiles })
$reg = Join-Path $work 'mod-registry'
if (-not $SkipRegistry) {
    Remove-Item -Recurse -Force $reg -ErrorAction SilentlyContinue
    Run $tool registry --legacy $legacy --out $reg --ir-root (Join-Path $root 'work\ir') @regSpecs
    # new locations: tile (DR2 loading art) and rally-plate logo textures under /Game/AcrXs/Locations/<Row>/ in the registry container
    $logoDir = Join-Path $work 'location-logos'
    & pwsh -NoProfile -File (Join-Path $root 'scripts\menu-location-logos.ps1') -Specs ($regSpecs -join ';') -Out $logoDir | Out-Host
    if ($LASTEXITCODE -ne 0) { throw 'menu-location-logos.ps1 failed' }
    $artDir = Join-Path $root 'work\dr2\menu-art\frontend\streamed_textures\loading'
    if (-not (Test-Path $artDir)) { & pwsh -NoProfile -File (Join-Path $root 'scripts\prepare-menu-art.ps1') | Out-Host }
    Run $tool menu-locations --legacy $legacy --out $reg --art-dir $artDir --logo-dir $logoDir --preview (Join-Path $root 'work\acr\menu-preview\locations') @regSpecs
    Remove-Item (Join-Path $dist 'zz_acrxs_registry_P.*') -ErrorAction SilentlyContinue
    Run $Retoc to-zen --version UE5_6 $reg (Join-Path $dist 'zz_acrxs_registry_P.utoc')
}

if ($Verify -and -not $SkipRegistry) {
    $check = Join-Path $work 'check'
    $full = Join-Path $check 'acr\Content\Paks'
    Remove-Item -Recurse -Force $check -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force $full | Out-Null
    Get-ChildItem $paks -File | % { New-Item -ItemType HardLink -Path (Join-Path $full $_.Name) -Target $_.FullName | Out-Null }
    Get-ChildItem $dist -File 'zz_acrxs_*' | % { New-Item -ItemType HardLink -Path (Join-Path $full $_.Name) -Target $_.FullName | Out-Null }
    $specDir = Join-Path $check 'specs'
    New-Item -ItemType Directory -Force $specDir | Out-Null
    $regSpecs | % { Copy-Item $_ $specDir }
    Run $tool verify --vanilla $vanilla --game $check --spec $specDir --ir-root (Join-Path $root 'work\ir') --out (Join-Path $check 'verify.txt')
    $rtPaks = Join-Path $check 'roundtrip-paks'
    New-Item -ItemType Directory -Force $rtPaks | Out-Null
    Copy-Item (Join-Path $paks 'global.*'), (Join-Path $dist 'zz_acrxs_registry_P.*') $rtPaks
    $rt = Join-Path $check 'roundtrip'
    Run $Retoc to-legacy --version UE5_6 --no-shaders $rtPaks $rt
    $uexp = @(Get-ChildItem $reg -Recurse -File -Filter *.uexp)
    $diff = @($uexp | ? {
        $o = Join-Path $rt ($_.FullName.Substring($reg.Length + 1))
        -not (Test-Path $o) -or (Get-FileHash $o).Hash -ne (Get-FileHash $_.FullName).Hash })
    if ($diff) { throw "registry round trip differs: $($diff.Name -join ', ')" }
    Write-Host "registry round trip: $($uexp.Count) tables' export data byte-identical"
}

Get-ChildItem $dist 'zz_acrxs_*' | Format-Table Name, @{ n = 'MB'; e = { [math]::Round($_.Length / 1MB, 2) } }
