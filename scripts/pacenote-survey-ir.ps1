<#
.SYNOPSIS
  Read-only pacenote survey over existing stage IRs (work/ir/<id>/stage.json): tallies DR2 call kinds, severities, modifiers and
  spoken distances and flags what config/pacenote-map.toml does not map. Never touches the DR2 install or work/dr2.
.PARAMETER All   survey every IR under work/ir (default: only the enabled stages of config/stages.toml)
#>
param(
    [switch]$All,
    [string]$Config = (Join-Path (Split-Path $PSScriptRoot) 'config\stages.toml'),
    [string]$Map = (Join-Path (Split-Path $PSScriptRoot) 'config\pacenote-map.toml'),
    [string]$Out = (Join-Path (Split-Path $PSScriptRoot) 'work\acr\batch\pacenote-survey.md')
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
. (Join-Path $PSScriptRoot 'stages-lib.ps1')

# keys of the mapped TOML sections
$sections = @{}; $cur = $null
foreach ($l in Get-Content $Map -Encoding UTF8) {
    $t = $l.Trim()
    if ($t -match '^\[([a-z_]+)\]$') { $cur = $Matches[1]; $sections[$cur] = @{}; continue }
    if ($cur -and $t -match '^"?([A-Za-z0-9_]+)"?\s*=') { $sections[$cur][$Matches[1]] = $true }
}
$ids = if ($All) { Get-ChildItem (Join-Path $root 'work\ir') -Directory | ? { Test-Path "$($_.FullName)\stage.json" } | % Name }
       else { (Read-StagesToml $Config).Stages | ? { $_.enabled } | % { $_.dr2 } }

$tally = @{ kind = @{}; severity = @{}; modifier = @{}; distance = @{}; direction = @{} }
$perStage = @()
function Add([string]$cat, [string]$key, [string]$stage) {
    if (-not $tally[$cat].ContainsKey($key)) { $tally[$cat][$key] = @{ n = 0; stages = [System.Collections.Generic.HashSet[string]]::new() } }
    $tally[$cat][$key].n++; [void]$tally[$cat][$key].stages.Add($stage)
}
foreach ($id in $ids) {
    $p = Join-Path $root "work\ir\$id\stage.json"
    if (-not (Test-Path $p)) { $perStage += [pscustomobject]@{ stage = $id; tokens = 0; unmapped = 'no IR' }; continue }
    $j = Get-Content $p -Raw | ConvertFrom-Json
    $un = [System.Collections.Generic.List[string]]::new()
    foreach ($t in $j.pacenotes.tokens) {
        Add kind $t.kind $id
        switch ($t.kind) {
            'corner' {
                Add direction "$($t.direction)" $id
                Add severity "$($t.severity)" $id
                if (-not $sections.direction.ContainsKey("$($t.direction)")) { $un.Add("direction $($t.direction)") }
                if (-not $sections.severity.ContainsKey("$($t.severity)")) { $un.Add("severity $($t.severity)") }
                foreach ($m in $t.modifiers) {
                    Add modifier "$m" $id
                    # unmapped modifiers are dropped quietly by stage-build; counted here so the map can be extended knowingly
                    if (-not $sections.modifiers.ContainsKey("$m")) { $un.Add("modifier $m") }
                }
            }
            'distance' { if ($null -ne $t.distance_call_m) { Add distance "$($t.distance_call_m)" $id } }
            'finish' { }
            default { $un.Add("kind $($t.kind) type $($t.type)") }
        }
    }
    $perStage += [pscustomobject]@{
        stage = $id; tokens = @($j.pacenotes.tokens).Count
        unmapped = ($un | Group-Object | Sort-Object Count -Descending | % { "$($_.Name) x$($_.Count)" }) -join '; '
    }
}
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("# Pacenote survey over $($ids.Count) stage IRs")
[void]$sb.AppendLine("`nGenerated by scripts/pacenote-survey-ir.ps1 against config/pacenote-map.toml. 'Unmapped' = dropped by stage-build (logged in each stage report).`n")
foreach ($cat in 'kind', 'direction', 'severity', 'modifier', 'distance') {
    [void]$sb.AppendLine("## $cat`n`n| value | calls | stages | mapped |`n|---|---:|---:|---|")
    $sec = switch ($cat) { 'severity' { 'severity' } 'direction' { 'direction' } 'modifier' { 'modifiers' } 'distance' { 'distance' } default { $null } }
    foreach ($k in ($tally[$cat].Keys | Sort-Object)) {
        $m = if ($cat -eq 'kind') { if ($k -in 'corner', 'distance', 'finish') { 'yes' } else { 'NO' } }
             elseif ($cat -eq 'distance') { if ($sections.distance.ContainsKey($k)) { 'as And' } else { 'straight row (Dist*)' } }
             elseif ($sections[$sec].ContainsKey($k)) { 'yes' } else { 'NO' }
        [void]$sb.AppendLine("| $k | $($tally[$cat][$k].n) | $($tally[$cat][$k].stages.Count) | $m |")
    }
    [void]$sb.AppendLine()
}
[void]$sb.AppendLine("## Per stage`n`n| stage | tokens | unmapped |`n|---|---:|---|")
foreach ($s in $perStage) { [void]$sb.AppendLine("| $($s.stage) | $($s.tokens) | $($s.unmapped) |") }
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
Set-Content $Out $sb.ToString() -Encoding UTF8
Write-Host "pacenote survey -> $Out"
$sb.ToString() -split "`n" | Select-Object -First 70 | Write-Host
