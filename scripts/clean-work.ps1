<#
.SYNOPSIS
  Frees disk space in work\ by deleting REGENERABLE data. Dry run unless -Force: nothing is deleted without it.

.DESCRIPTION
  Lists every category with the space deleting it would really free (hard links are accounted for: a file shared with the
  game's ~mods or another folder only frees its bytes when every link is deleted). With -Force the selected categories are removed.

  Categories (-Include, default = the ones marked *):
    scratch *            work\acr\additive\mod-build-* / overlay-* / mod-stage-* left by killed or -KeepTemp builds
    dr2-location-cache * work\dr2\cache\<country>__<location>: extracted DR2 location archives, 2-4 GB each (re-extracted on demand)
    ir-built *           heavy IR (render\ + textures\, ~1.7 GB per stage) of stages whose container is built and recorded ok in
                         work\acr\batch\state; stage.json + collision glbs stay, ir-pruned.json keeps the stage "unchanged"
    experiments *        old experiment output nothing in the pipeline reads: work\acr\verify-fast, dist-v1.11, mod-*, legacy-vanilla-test,
                         v1.8-previews, tmp-additive-build, additive\mod-registry-test
    ir-all               heavy IR of EVERY stage that has a stage.json, built or not (use with build-stages.ps1 -PrepareOnDemand,
                         which regenerates it stage by stage, ~30 s each)
    dr2-layer-cache      work\dr2\cache\game* (shared DR2 layers, ~5 GB; re-extracted on demand)
    previews             work\acr\menu-preview (menu image previews, regenerated by builds)
    stale-dist           work\acr\additive\dist\zz_acrdirt_* (containers from before the AcrDirt -> AcrXs rename). They free space
                         only when the game's ~mods links are gone too: run scripts\install-stages.ps1 -Uninstall first (it also removes
                         the legacy zz_acrdirt_* files there), otherwise the data stays alive through ~mods.

  Never touched: work\ir light files, work\acr\legacy-vanilla, work\acr\additive\legacy, work\acr\specs, work\acr\batch (state,
  reports), work\bin, work\dr2\menu-art, and everything outside work\ (the game folder, ~mods).

.PARAMETER Include   categories to process (comma separated or an array); default is the * set above
.PARAMETER Force     actually delete (without it this is a dry run)

.EXAMPLE
  pwsh scripts\clean-work.ps1                              # what would be freed
  pwsh scripts\clean-work.ps1 -Force                       # delete the default set
  pwsh scripts\clean-work.ps1 -Include ir-all,dr2-location-cache -Force
#>
param(
    [string[]]$Include,
    [switch]$Force
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
. (Join-Path $PSScriptRoot 'disk-lib.ps1')
$defaults = 'scratch', 'dr2-location-cache', 'ir-built', 'experiments'
$all = $defaults + 'ir-all', 'dr2-layer-cache', 'previews', 'stale-dist'
$sel = @(if ($Include) { $Include | % { $_ -split '[,;\s]+' } | ? { $_ } } else { $defaults })
$bad = @($sel | ? { $_ -notin $all })
if ($bad) { throw "unknown category: $($bad -join ', '). Known: $($all -join ', ')" }

$work = Join-Path $root 'work'
$additive = Join-Path $work 'acr\additive'
$dist = Join-Path $additive 'dist'
$state = Join-Path $work 'acr\batch\state'

function Safe([string]$p) {   # only ever delete inside <repo>\work
    $full = [IO.Path]::GetFullPath($p)
    if (-not $full.StartsWith($work + '\', [StringComparison]::OrdinalIgnoreCase)) { throw "refusing to touch $full (outside $work)" }
    $full
}

# category -> @{ Paths = whole folders/files to delete; Irs = stage IR dirs whose heavy part goes }
function Get-Targets([string]$cat) {
    $paths = @(); $irs = @()
    switch ($cat) {
        'scratch' { $paths = @(foreach ($pre in 'mod-build-', 'overlay-', 'mod-stage-') { Get-ChildItem $additive -Directory -Filter "$pre*" -ErrorAction SilentlyContinue | % FullName }) }
        'dr2-location-cache' { $paths = @(Get-ChildItem (Join-Path $work 'dr2\cache') -Directory -Filter '*__*' -ErrorAction SilentlyContinue | % FullName) }
        'dr2-layer-cache' { $paths = @(Get-ChildItem (Join-Path $work 'dr2\cache') -Directory -ErrorAction SilentlyContinue | ? { $_.Name -notlike '*__*' } | % FullName) }
        'previews' { $paths = @(Join-Path $work 'acr\menu-preview') }
        'experiments' {
            $paths = @('verify-fast', 'dist-v1.11', 'legacy-vanilla-test', 'v1.8-previews', 'tmp-additive-build') | % { Join-Path $work "acr\$_" }
            $paths += @(Get-ChildItem (Join-Path $work 'acr') -Directory -Filter 'mod-*' -ErrorAction SilentlyContinue | % FullName)
            $paths += Join-Path $additive 'mod-registry-test'
        }
        'stale-dist' { $paths = @(Get-ChildItem $dist -File -Filter 'zz_acrdirt_*' -ErrorAction SilentlyContinue | % FullName) }
        { $_ -in 'ir-built', 'ir-all' } {
            foreach ($d in Get-ChildItem (Join-Path $work 'ir') -Directory -ErrorAction SilentlyContinue) {
                if (-not (Test-Path (Join-Path $d.FullName 'stage.json'))) { continue }
                if (-not ((Test-Path (Join-Path $d.FullName 'render')) -or (Test-Path (Join-Path $d.FullName 'textures')))) { continue }
                if ($cat -eq 'ir-built') {
                    # a stage counts as built when a state file records ok AND its current-name container is in dist
                    $ok = $false
                    foreach ($sf in Get-ChildItem $state -Filter '*.json' -ErrorAction SilentlyContinue) {
                        $idl = $sf.BaseName
                        if ((Test-Path (Join-Path $dist "zz_acrxs_s_${idl}_P.utoc")) -and (Get-Content $sf.FullName -Raw | ConvertFrom-Json).ok) {
                            $acr = $idl
                            # state ids are acr ids (acrxsgr02r4); map to the dr2 id through the spec
                            $spec = Join-Path $work "acr\specs\$acr.json"
                            if ((Test-Path $spec) -and (Get-Content $spec -Raw | ConvertFrom-Json).Stage -eq $d.Name) { $ok = $true; break }
                        }
                    }
                    if (-not $ok) { continue }
                }
                $irs += $d.FullName
            }
        }
    }
    @{ Paths = @($paths | ? { $_ -and (Test-Path $_) }); Irs = $irs }
}

$total = 0
$rows = foreach ($cat in $sel) {
    $t = Get-Targets $cat
    $heavy = @($t.Irs | % { Join-Path $_ 'render'; Join-Path $_ 'textures' })
    $freed = Get-FreedMB (@($t.Paths) + $heavy)
    $total += $freed
    [pscustomobject]@{ Category = $cat; Items = @($t.Paths).Count + @($t.Irs).Count; FreedGB = [math]::Round($freed / 1024, 2); Targets = $t }
}
$rows | Select-Object Category, Items, FreedGB | Format-Table -AutoSize | Out-String | Write-Host
Write-Host ("total that deleting these frees: {0:N1} GB" -f ($total / 1024))
$free = Get-DriveFreeMB $root
Write-Host ("free now on {0}: {1:N1} GB" -f (Split-Path -Qualifier $root), ($free / 1024))
if (-not $Force) { Write-Host 'dry run: nothing deleted. Re-run with -Force to delete.'; return }

foreach ($r in $rows) {
    foreach ($p in $r.Targets.Paths) { Remove-Item -LiteralPath (Safe $p) -Recurse -Force -ErrorAction SilentlyContinue }
    foreach ($ir in $r.Targets.Irs) { [void](Remove-StageIrHeavy (Safe $ir)) }
    Write-Host "cleaned $($r.Category) ($($r.Items) item(s))"
}
Write-Host ("free after: {0:N1} GB" -f ((Get-DriveFreeMB $root) / 1024))
